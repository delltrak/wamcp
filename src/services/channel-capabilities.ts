import type { ChannelType } from "../types/channel.types.js";

interface Feature {
  supported: boolean;
  tools: string[];
  requirements: string[];
  notes?: string;
}

/** Implementation support, not authorization or a probe of the remote account. */
export function getChannelCapabilities(channel: ChannelType): Record<string, Feature> {
  const baileys = channel === "baileys";
  const feature = (
    supported: boolean,
    tools: string[],
    requirements: string[] = [],
    notes?: string,
  ): Feature => ({
    supported,
    tools,
    requirements: supported ? requirements : [],
    ...(notes ? { notes } : {}),
  });
  const groupWrites = [
    "Connected account with the required group role",
    "WA_GROUP_WRITES_ENABLED=true or WA_APP_STATE_WRITES_ENABLED=true",
  ];
  return {
    individualMessages: feature(
      true,
      [
        "wa_send_text",
        "wa_send_image",
        "wa_send_video",
        "wa_send_audio",
        "wa_send_document",
        "wa_send_sticker",
        "wa_send_contact",
        "wa_send_location",
      ],
      ["Connected account", "Redis queue"],
      baileys
        ? undefined
        : "Individual recipients only; Meta messaging-window and template rules apply.",
    ),
    groupMessages: feature(
      baileys,
      ["wa_send_text", "wa_send_group_mention_all"],
      ["Connected account with permission to send to the group", "Redis queue"],
      "Native @all additionally depends on account support; participant mentions are the fallback.",
    ),
    authenticationOtp: feature(
      !baileys,
      ["wa_send_otp"],
      [
        "Cloud API credentials",
        "Approved AUTHENTICATION template with copy-code button",
        "WA_OTP_ENCRYPTION_KEY",
        "Redis queue",
        "Backend-managed code expiry and single use",
      ],
    ),
    authenticationTemplates: feature(
      !baileys,
      ["wa_list_authentication_templates"],
      [
        "Cloud API credentials",
        "businessId must be the WABA ID",
        "whatsapp_business_management permission",
      ],
    ),
    jobStatus: feature(
      true,
      ["wa_get_job_status"],
      ["Redis queue"],
      "Read-only; retained jobs only. Queue completion is not proof of recipient delivery.",
    ),
    reactions: feature(true, ["wa_send_reaction"], ["Connected account"]),
    reactionHistory: feature(
      baileys,
      ["wa_get_message_reactions"],
      [],
      "Locally observed reactions only.",
    ),
    participantReceipts: feature(
      baileys,
      ["wa_get_message_receipts"],
      [],
      "Locally observed receipts; missing receipts do not prove unread messages.",
    ),
    markRead: feature(true, ["wa_mark_read"], ["Connected account"]),
    markPlayed: feature(
      baileys,
      ["wa_mark_played"],
      ["Connected account", "Stored incoming audio/video message"],
    ),
    presence: feature(
      baileys,
      ["wa_send_presence", "wa_subscribe_presence"],
      ["Connected account"],
      "Describes this adapter's implementation, not every feature offered by Meta.",
    ),
    nativeInteractiveMessages: feature(
      !baileys,
      ["wa_send_buttons", "wa_send_list"],
      ["Connected account"],
      baileys
        ? "These tools send a text fallback on Baileys, not native interactive controls."
        : undefined,
    ),
    editMessages: feature(
      baileys,
      ["wa_edit_message"],
      ["Connected account", "WhatsApp edit eligibility"],
    ),
    deleteMessages: feature(
      baileys,
      ["wa_delete_message"],
      ["Connected account", "WhatsApp revoke eligibility"],
    ),
    forwardMessages: feature(
      baileys,
      ["wa_forward_message"],
      ["Connected account", "Stored source message"],
    ),
    viewOnce: feature(baileys, ["wa_send_view_once"], ["Connected account"]),
    mediaAlbums: feature(baileys, ["wa_send_media_album"], ["Connected account", "Redis queue"]),
    linkPreviews: feature(
      true,
      ["wa_send_link_preview"],
      ["Connected account"],
      baileys
        ? "Supports custom preview metadata."
        : "Preview generated by Meta; custom metadata/thumbnails are unsupported.",
    ),
    polls: feature(baileys, ["wa_send_poll", "wa_get_poll_results"], ["Connected account"]),
    events: feature(baileys, ["wa_send_event", "wa_get_event_responses"], ["Connected account"]),
    groups: feature(
      baileys,
      ["wa_create_group", "wa_get_group_info"],
      groupWrites,
      "Read operations do not require write flags; writes also depend on the caller's role.",
    ),
    communities: feature(
      baileys,
      ["wa_create_community", "wa_list_communities"],
      groupWrites,
      "Read operations do not require write flags; writes also depend on the caller's role.",
    ),
    newsletters: feature(
      baileys,
      ["wa_newsletter_follow", "wa_newsletter_send"],
      ["Connected account", "Channel membership/role required by WhatsApp"],
    ),
    statusStories: feature(
      baileys,
      ["wa_send_text_status", "wa_get_status_viewers"],
      ["Connected account", "Status audience requirements"],
    ),
    chatModifications: feature(
      baileys,
      ["wa_archive_chat", "wa_pin_chat", "wa_mute_chat"],
      ["Connected account", "WA_APP_STATE_WRITES_ENABLED=true"],
    ),
    labels: feature(
      baileys,
      ["wa_list_labels", "wa_create_label"],
      ["WhatsApp Business account", "WA_APP_STATE_WRITES_ENABLED=true for writes"],
    ),
    privacy: feature(
      baileys,
      ["wa_get_privacy_settings", "wa_update_privacy"],
      ["WA_APP_STATE_WRITES_ENABLED=true for writes"],
    ),
    storedSearch: feature(
      true,
      ["wa_search_messages"],
      [],
      "Searches this instance's locally stored messages, not all WhatsApp history.",
    ),
    messageHistory: feature(
      baileys,
      ["wa_get_messages", "wa_fetch_message_history"],
      ["Stored messages; connected account for fetching history"],
    ),
    scheduledSends: feature(
      true,
      ["wa_schedule_message"],
      [
        "WA_SCHEDULER_ENABLED=true",
        "Running scheduler",
        "Redis queue",
        "Connected account when due",
      ],
    ),
  };
}
